  /* ---------- core/linalg.js ---------- */
  /* ==========================================================================
     ode_julia / core / linalg

     The linear algebra the stiff solvers need, and nothing else.

     Every stiff method here spends almost all of its time in one place: solving
     (W)x = b where W = I/(γh) − J, or M − γhJ, or the complex pair Radau needs.
     So the shapes are chosen for that and not for generality.

       - Dense matrices are column-major in one Float64Array. LU walks columns.
       - Sparse matrices are compressed-column (CSC), which is what a Jacobian
         built column by column already is, and what the left-looking LU below
         wants.
       - Factorisations own their buffers and are reused. Forming W and
         factorising it is the expensive part of a stiff step, and the whole
         point of the caches above this file is to do it as rarely as possible;
         nothing here allocates once it has been constructed.

     Complex arithmetic is split into parallel re/im arrays rather than an array
     of objects: RadauIIA5 solves one complex n×n system per Newton iteration,
     and an array of {re, im} would allocate 2n objects per solve.
     ========================================================================== */

  /**
   * A square matrix, column-major: A[i][j] is data[j * n + i].
   *
   * Column-major because both LU factorisations here are column algorithms --
   * the inner loops run down a column, which is then contiguous.
   */
  class DenseMatrix {
    constructor(n, data) {
      this.n = n;
      this.data = data || new Float64Array(n * n);
    }

    static zeros(n) { return new DenseMatrix(n); }

    /** A[i][j] = v */
    set(i, j, v) { this.data[j * this.n + i] = v; }

    /** A[i][j] */
    get(i, j) { return this.data[j * this.n + i]; }

    fill(v) { this.data.fill(v); }

    /** this <- 0, then the diagonal <- v. */
    setIdentity(v = 1) {
      this.data.fill(0);
      for (let i = 0; i < this.n; i++) this.data[i * this.n + i] = v;
    }

    /** y <- A x. y may not alias x. */
    apply(x, y) {
      const { n, data } = this;
      y.fill(0);
      for (let j = 0; j < n; j++) {
        const xj = x[j];
        if (xj === 0) continue;
        const base = j * n;
        for (let i = 0; i < n; i++) y[i] += data[base + i] * xj;
      }
      return y;
    }
  }

  /**
   * Compressed sparse column.
   *
   * colPtr has n+1 entries; the entries of column j are rowIdx/values over
   * [colPtr[j], colPtr[j+1]), with the row indices sorted ascending. Sorted
   * rows are not merely tidy: the triangular solves below rely on it.
   */
  class CSC {
    constructor(n, colPtr, rowIdx, values) {
      this.n = n;
      this.colPtr = colPtr;
      this.rowIdx = rowIdx;
      this.values = values || new Float64Array(rowIdx.length);
    }

    get nnz() { return this.colPtr[this.n]; }

    /** A copy of the sparsity with a fresh value array. */
    cloneStructure() {
      return new CSC(this.n, this.colPtr, this.rowIdx, new Float64Array(this.rowIdx.length));
    }

    /** y <- A x. y may not alias x. */
    apply(x, y) {
      const { n, colPtr, rowIdx, values } = this;
      y.fill(0);
      for (let j = 0; j < n; j++) {
        const xj = x[j];
        if (xj === 0) continue;
        for (let k = colPtr[j]; k < colPtr[j + 1]; k++) y[rowIdx[k]] += values[k] * xj;
      }
      return y;
    }

    /** Dense copy, for small problems and for checking. */
    toDense() {
      const A = DenseMatrix.zeros(this.n);
      for (let j = 0; j < this.n; j++) {
        for (let k = this.colPtr[j]; k < this.colPtr[j + 1]; k++) A.set(this.rowIdx[k], j, this.values[k]);
      }
      return A;
    }
  }

  /**
   * Build a CSC from triplets, summing duplicates and sorting rows.
   *
   * Used to turn a Jacobian pattern given as (i, j) pairs into something the
   * factorisations can take.
   */
  function cscFromTriplets(n, rows, cols, vals) {
    const count = new Int32Array(n + 1);
    const m = rows.length;
    for (let k = 0; k < m; k++) count[cols[k] + 1]++;
    for (let j = 0; j < n; j++) count[j + 1] += count[j];
    const colPtr = Int32Array.from(count);
    const rowIdx = new Int32Array(m);
    const values = new Float64Array(m);
    const at = Int32Array.from(count);
    for (let k = 0; k < m; k++) {
      const p = at[cols[k]]++;
      rowIdx[p] = rows[k];
      values[p] = vals ? vals[k] : 0;
    }
    // Sort each column by row and fold duplicates together.
    const outPtr = new Int32Array(n + 1);
    const outRow = new Int32Array(m);
    const outVal = new Float64Array(m);
    let w = 0;
    const order = [];
    for (let j = 0; j < n; j++) {
      const lo = colPtr[j];
      const hi = colPtr[j + 1];
      order.length = 0;
      for (let k = lo; k < hi; k++) order.push(k);
      order.sort((a, b) => rowIdx[a] - rowIdx[b]);
      let last = -1;
      for (const k of order) {
        const r = rowIdx[k];
        if (r === last) { outVal[w - 1] += values[k]; continue; }
        outRow[w] = r;
        outVal[w] = values[k];
        w++;
        last = r;
      }
      outPtr[j + 1] = w;
    }
    return new CSC(n, outPtr, outRow.slice(0, w), outVal.slice(0, w));
  }

  /* ==========================================================================
     Dense LU with partial pivoting
     ========================================================================== */

  /**
   * Right-looking LU with partial pivoting, in place, column-major.
   *
   * Reused across Newton iterations and across steps: `factor` overwrites the
   * internal buffer and nothing else allocates, so a solver that re-forms W
   * every step still allocates only once.
   */
  class DenseLU {
    constructor(n) {
      this.n = n;
      this.lu = new Float64Array(n * n);
      this.piv = new Int32Array(n);
      this.singular = false;
    }

    /**
     * Factorise a copy of A (column-major Float64Array or DenseMatrix).
     * @returns {boolean} false if a zero pivot was met, and the factor is unusable.
     */
    factor(A) {
      const n = this.n;
      const a = this.lu;
      a.set(A.data || A);
      const piv = this.piv;
      this.singular = false;
      for (let k = 0; k < n; k++) {
        // Pivot: the largest entry at or below the diagonal of column k.
        let p = k;
        let big = Math.abs(a[k * n + k]);
        for (let i = k + 1; i < n; i++) {
          const v = Math.abs(a[k * n + i]);
          if (v > big) { big = v; p = i; }
        }
        piv[k] = p;
        if (big === 0) { this.singular = true; return false; }
        if (p !== k) {
          for (let j = 0; j < n; j++) {
            const o1 = j * n + k;
            const o2 = j * n + p;
            const t = a[o1]; a[o1] = a[o2]; a[o2] = t;
          }
        }
        const dinv = 1 / a[k * n + k];
        const colK = k * n;
        for (let i = k + 1; i < n; i++) a[colK + i] *= dinv;
        // Rank-1 update of the trailing submatrix.
        for (let j = k + 1; j < n; j++) {
          const akj = a[j * n + k];
          if (akj === 0) continue;
          const colJ = j * n;
          for (let i = k + 1; i < n; i++) a[colJ + i] -= a[colK + i] * akj;
        }
      }
      return true;
    }

    /**
     * Solve LUx = Pb, overwriting b with x.
     *
     * Every interchange is applied to b first, before any substitution. That is
     * forced by the factorisation above, which swaps the whole row -- the
     * already-computed multipliers included -- so the stored L is the L of the
     * fully permuted matrix. Interleaving a swap with each elimination, as
     * LINPACK does, is correct only for a factorisation that leaves the earlier
     * columns alone, and pairing the two conventions gives a plausible wrong
     * answer on any matrix that actually needs pivoting.
     */
    solve(b) {
      const n = this.n;
      const a = this.lu;
      const piv = this.piv;
      for (let k = 0; k < n; k++) {
        const p = piv[k];
        if (p !== k) { const t = b[k]; b[k] = b[p]; b[p] = t; }
      }
      for (let k = 0; k < n; k++) {
        const bk = b[k];
        if (bk === 0) continue;
        const colK = k * n;
        for (let i = k + 1; i < n; i++) b[i] -= a[colK + i] * bk;
      }
      for (let k = n - 1; k >= 0; k--) {
        const colK = k * n;
        const bk = (b[k] /= a[colK + k]);
        if (bk === 0) continue;
        for (let i = 0; i < k; i++) b[i] -= a[colK + i] * bk;
      }
      return b;
    }
  }

  /* ==========================================================================
     Complex dense LU
     ========================================================================== */

  /**
   * The same algorithm over the complex numbers, with re and im held apart.
   *
   * RadauIIA5 needs exactly one of these: its 3×3 stage system decouples, over
   * the eigenbasis of the inverse Butcher matrix, into one real n×n solve and
   * one complex n×n solve. Doing it that way rather than as a real 3n×3n system
   * is the difference between 3n³/3 and 27n³/3 of work per factorisation.
   */
  class ComplexDenseLU {
    constructor(n) {
      this.n = n;
      this.re = new Float64Array(n * n);
      this.im = new Float64Array(n * n);
      this.piv = new Int32Array(n);
      this.singular = false;
    }

    /** Factorise the matrix given as separate real and imaginary parts. */
    factor(Are, Aim) {
      const n = this.n;
      const re = this.re;
      const im = this.im;
      re.set(Are);
      im.set(Aim);
      const piv = this.piv;
      this.singular = false;
      for (let k = 0; k < n; k++) {
        let p = k;
        let big = Math.abs(re[k * n + k]) + Math.abs(im[k * n + k]);
        for (let i = k + 1; i < n; i++) {
          const v = Math.abs(re[k * n + i]) + Math.abs(im[k * n + i]);
          if (v > big) { big = v; p = i; }
        }
        piv[k] = p;
        if (big === 0) { this.singular = true; return false; }
        if (p !== k) {
          for (let j = 0; j < n; j++) {
            const o1 = j * n + k;
            const o2 = j * n + p;
            let t = re[o1]; re[o1] = re[o2]; re[o2] = t;
            t = im[o1]; im[o1] = im[o2]; im[o2] = t;
          }
        }
        // 1 / (dr + i di), by the scaled form that avoids overflow in dr² + di².
        const dr = re[k * n + k];
        const di = im[k * n + k];
        let invR;
        let invI;
        if (Math.abs(dr) >= Math.abs(di)) {
          const r = di / dr;
          const den = dr + di * r;
          invR = 1 / den;
          invI = -r / den;
        } else {
          const r = dr / di;
          const den = dr * r + di;
          invR = r / den;
          invI = -1 / den;
        }
        const colK = k * n;
        for (let i = k + 1; i < n; i++) {
          const ar = re[colK + i];
          const ai = im[colK + i];
          re[colK + i] = ar * invR - ai * invI;
          im[colK + i] = ar * invI + ai * invR;
        }
        for (let j = k + 1; j < n; j++) {
          const colJ = j * n;
          const br = re[colJ + k];
          const bi = im[colJ + k];
          if (br === 0 && bi === 0) continue;
          for (let i = k + 1; i < n; i++) {
            const ar = re[colK + i];
            const ai = im[colK + i];
            re[colJ + i] -= ar * br - ai * bi;
            im[colJ + i] -= ar * bi + ai * br;
          }
        }
      }
      return true;
    }

    /**
     * Solve in place; br/bi are overwritten with the real and imaginary parts.
     * The interchanges come first, for the reason given in DenseLU.solve.
     */
    solve(br, bi) {
      const n = this.n;
      const re = this.re;
      const im = this.im;
      const piv = this.piv;
      for (let k = 0; k < n; k++) {
        const p = piv[k];
        if (p !== k) {
          let t = br[k]; br[k] = br[p]; br[p] = t;
          t = bi[k]; bi[k] = bi[p]; bi[p] = t;
        }
      }
      for (let k = 0; k < n; k++) {
        const xr = br[k];
        const xi = bi[k];
        if (xr === 0 && xi === 0) continue;
        const colK = k * n;
        for (let i = k + 1; i < n; i++) {
          const ar = re[colK + i];
          const ai = im[colK + i];
          br[i] -= ar * xr - ai * xi;
          bi[i] -= ar * xi + ai * xr;
        }
      }
      for (let k = n - 1; k >= 0; k--) {
        const colK = k * n;
        const dr = re[colK + k];
        const di = im[colK + k];
        const xr = br[k];
        const xi = bi[k];
        let qr;
        let qi;
        if (Math.abs(dr) >= Math.abs(di)) {
          const r = di / dr;
          const den = dr + di * r;
          qr = (xr + xi * r) / den;
          qi = (xi - xr * r) / den;
        } else {
          const r = dr / di;
          const den = dr * r + di;
          qr = (xr * r + xi) / den;
          qi = (xi * r - xr) / den;
        }
        br[k] = qr;
        bi[k] = qi;
        if (qr === 0 && qi === 0) continue;
        for (let i = 0; i < k; i++) {
          const ar = re[colK + i];
          const ai = im[colK + i];
          br[i] -= ar * qr - ai * qi;
          bi[i] -= ar * qi + ai * qr;
        }
      }
    }
  }

  /* ==========================================================================
     Sparse LU: Gilbert-Peierls, left-looking, partial pivoting
     ========================================================================== */

  /**
   * Reverse Cuthill-McKee on the symmetrised pattern.
   *
   * A fill-reducing permutation. For a chemical Jacobian -- banded-ish once the
   * species are ordered by how they react -- it is usually worth several times
   * its cost, and where it is not, the caller compares the measured fill against
   * dense and picks the cheaper. Returns the new-to-old ordering.
   */
  function reverseCuthillMcKee(n, colPtr, rowIdx) {
    // Symmetrise: adjacency of A + Aᵀ.
    const deg = new Int32Array(n);
    for (let j = 0; j < n; j++) {
      for (let k = colPtr[j]; k < colPtr[j + 1]; k++) {
        const i = rowIdx[k];
        if (i === j) continue;
        deg[i]++;
        deg[j]++;
      }
    }
    const start = new Int32Array(n + 1);
    for (let j = 0; j < n; j++) start[j + 1] = start[j] + deg[j];
    const adj = new Int32Array(start[n]);
    const at = Int32Array.from(start);
    for (let j = 0; j < n; j++) {
      for (let k = colPtr[j]; k < colPtr[j + 1]; k++) {
        const i = rowIdx[k];
        if (i === j) continue;
        adj[at[i]++] = j;
        adj[at[j]++] = i;
      }
    }

    const order = new Int32Array(n);
    const seen = new Uint8Array(n);
    let w = 0;
    const nbrs = [];
    // One component, breadth first from the vertex of least degree at or after
    // `from`, each vertex's neighbours taken in increasing degree.
    const component = (from) => {
      let root = from;
      let best = Infinity;
      for (let v = from; v < n; v++) {
        if (seen[v]) continue;
        const d = start[v + 1] - start[v];
        if (d < best) { best = d; root = v; }
      }
      seen[root] = 1;
      order[w++] = root;
      let head = w - 1;
      while (head < w) {
        const v = order[head++];
        nbrs.length = 0;
        for (let k = start[v]; k < start[v + 1]; k++) {
          const u = adj[k];
          if (!seen[u]) { seen[u] = 1; nbrs.push(u); }
        }
        nbrs.sort((a, b) => (start[a + 1] - start[a]) - (start[b + 1] - start[b]));
        for (const u of nbrs) order[w++] = u;
      }
    };
    for (let s = 0; s < n; s++) {
      if (seen[s]) continue;
      component(s);
    }
    // That loop moves past s whether or not the component it started reached s
    // -- the root is the least degree from s on, which need not be s -- so it
    // can pass vertices that no later component contains. The order then came
    // back short and padded with zeros: not a permutation, and a factorisation
    // through it reported the matrix singular or pivoted on garbage. Two
    // isolated vertices after a connected block were enough, and a Kompartment
    // model with its mass-balance audit on has dozens. Whatever it left is
    // ordered here; from s on nothing is unseen, so nothing is passed again.
    // Where it left nothing -- every case it got right -- the order is the one
    // it always gave.
    for (let s = 0; s < n && w < n; s++) {
      while (!seen[s]) component(s);
    }
    // Reversed: Cuthill-McKee reversed has strictly no more fill, usually less.
    const rcm = new Int32Array(n);
    for (let i = 0; i < n; i++) rcm[i] = order[n - 1 - i];
    return rcm;
  }

  /**
   * Left-looking sparse LU with partial pivoting (Gilbert and Peierls, 1988).
   *
   * Column j of L and U is found by solving a sparse triangular system against
   * the columns already computed. The cost is proportional to the number of
   * non-zeros in the factor rather than to n³, which is the whole reason to
   * bother; the depth-first search below is what finds, in time proportional to
   * the answer, which rows of the column can be non-zero.
   *
   * The pattern is fixed at construction (the Jacobian's), but the pivoting is
   * numeric, so the factor's pattern is discovered at each factorisation. That
   * is Gilbert-Peierls as written; a symbolic-once variant would need threshold
   * pivoting and is a different trade.
   */
  class SparseLU {
    /**
     * @param {number} n
     * @param {Int32Array} colPtr  pattern of the matrix to be factorised
     * @param {Int32Array} rowIdx
     * @param {Int32Array} [perm]  column ordering (new -> old), e.g. from RCM
     */
    constructor(n, colPtr, rowIdx, perm) {
      this.n = n;
      this.perm = perm || null;
      this.iperm = null;
      if (perm) {
        this.iperm = new Int32Array(n);
        for (let i = 0; i < n; i++) this.iperm[perm[i]] = i;
      }
      // Work space, all of it reused across factorisations.
      this.x = new Float64Array(n);          // the dense accumulator for one column
      this.mark = new Int32Array(n).fill(-1); // which column last touched a row
      this.stack = new Int32Array(n);
      this.pstack = new Int32Array(n);
      this.pattern = new Int32Array(n);      // the non-zero rows of the column
      this.piv = new Int32Array(n);          // row pivot chosen at each step
      this.pinv = new Int32Array(n).fill(-1); // old row -> position in the factor
      // The factor grows; start at a few times the matrix and double as needed.
      const guess = Math.max(4 * colPtr[n] + n, 16);
      this.Lp = new Int32Array(n + 1);
      this.Li = new Int32Array(guess);
      this.Lx = new Float64Array(guess);
      this.Up = new Int32Array(n + 1);
      this.Ui = new Int32Array(guess);
      this.Ux = new Float64Array(guess);
      this.singular = false;
      this.fill = 0;
    }

    _growL(need) {
      if (need <= this.Li.length) return;
      const cap = Math.max(need, this.Li.length * 2);
      const Li = new Int32Array(cap); Li.set(this.Li); this.Li = Li;
      const Lx = new Float64Array(cap); Lx.set(this.Lx); this.Lx = Lx;
    }

    _growU(need) {
      if (need <= this.Ui.length) return;
      const cap = Math.max(need, this.Ui.length * 2);
      const Ui = new Int32Array(cap); Ui.set(this.Ui); this.Ui = Ui;
      const Ux = new Float64Array(cap); Ux.set(this.Ux); this.Ux = Ux;
    }

    /**
     * Depth-first search from the non-zeros of column j of A, over the graph of
     * L, to find every row that can become non-zero. Returns the count, with the
     * rows written into this.pattern in topological order (last first).
     */
    _reach(colPtr, rowIdx, j, mark, top0) {
      const { stack, pstack, pattern, Lp, Li, pinv } = this;
      let top = top0;
      for (let p = colPtr[j]; p < colPtr[j + 1]; p++) {
        let i = rowIdx[p];
        if (mark[i] === j) continue;
        // Iterative DFS: the recursion would be n deep on a triangular matrix.
        let head = 0;
        stack[0] = i;
        while (head >= 0) {
          i = stack[head];
          const pi = pinv[i];
          let start;
          if (mark[i] !== j) {
            mark[i] = j;
            pstack[head] = pi < 0 ? 0 : Lp[pi];
          }
          start = pstack[head];
          let done = true;
          const end = pi < 0 ? 0 : Lp[pi + 1];
          for (let k = start; k < end; k++) {
            const child = Li[k];
            if (mark[child] === j) continue;
            pstack[head] = k + 1;
            stack[++head] = child;
            done = false;
            break;
          }
          if (done) {
            head--;
            pattern[--top] = i;
          }
        }
      }
      return top;
    }

    /**
     * Numeric factorisation of the matrix whose values are `values` over the
     * pattern this was built with.
     * @returns {boolean} false if a column was structurally or numerically empty.
     */
    factor(colPtr, rowIdx, values) {
      const n = this.n;
      const { x, mark, pattern, piv, pinv, perm } = this;
      mark.fill(-1);
      pinv.fill(-1);
      let lnz = 0;
      let unz = 0;
      this.singular = false;
      for (let k = 0; k < n; k++) {
        this.Lp[k] = lnz;
        this.Up[k] = unz;
        this._growL(lnz + n);
        this._growU(unz + n);
        const j = perm ? perm[k] : k;
        const top = this._reach(colPtr, rowIdx, j, mark, n);
        // Scatter column j of A into the dense accumulator.
        for (let t = top; t < n; t++) x[pattern[t]] = 0;
        for (let p = colPtr[j]; p < colPtr[j + 1]; p++) x[rowIdx[p]] = values[p];
        // Sparse triangular solve against the columns already done.
        for (let t = top; t < n; t++) {
          const i = pattern[t];
          const pi = pinv[i];
          if (pi < 0) continue;
          const xi = x[i];
          if (xi === 0) continue;
          for (let p = this.Lp[pi]; p < this.Lp[pi + 1]; p++) x[this.Li[p]] -= this.Lx[p] * xi;
        }
        // Pivot on the largest remaining entry that is not yet in U.
        let ipiv = -1;
        let big = 0;
        for (let t = top; t < n; t++) {
          const i = pattern[t];
          if (pinv[i] >= 0) continue;
          const v = Math.abs(x[i]);
          if (v > big) { big = v; ipiv = i; }
        }
        if (ipiv < 0 || big === 0) { this.singular = true; return false; }
        const pivot = x[ipiv];
        pinv[ipiv] = k;
        piv[k] = ipiv;
        // U gets the rows already pivoted, plus the pivot on the diagonal.
        for (let t = top; t < n; t++) {
          const i = pattern[t];
          const pi = pinv[i];
          if (pi < 0 || pi === k) continue;
          if (x[i] !== 0) { this.Ui[unz] = pi; this.Ux[unz] = x[i]; unz++; }
        }
        this.Ui[unz] = k; this.Ux[unz] = pivot; unz++;
        // L gets the rest, divided by the pivot.
        for (let t = top; t < n; t++) {
          const i = pattern[t];
          if (pinv[i] >= 0) continue;
          if (x[i] !== 0) { this.Li[lnz] = i; this.Lx[lnz] = x[i] / pivot; lnz++; }
        }
      }
      this.Lp[n] = lnz;
      this.Up[n] = unz;
      this.fill = lnz + unz;
      return true;
    }

    /** Solve LUx = Pb in place. */
    solve(b) {
      const n = this.n;
      const { piv, pinv, perm, x } = this;
      // Forward substitution in the factor's own order.
      x.set(b);
      for (let k = 0; k < n; k++) {
        const i = piv[k];
        const xk = x[i];
        if (xk === 0) continue;
        for (let p = this.Lp[k]; p < this.Lp[k + 1]; p++) x[this.Li[p]] -= this.Lx[p] * xk;
      }
      // Gather the pivoted entries into a compact vector, back-substitute in U.
      const y = b;
      for (let k = 0; k < n; k++) y[k] = x[piv[k]];
      for (let k = n - 1; k >= 0; k--) {
        const end = this.Up[k + 1] - 1;   // the diagonal, written last
        const yk = (y[k] /= this.Ux[end]);
        if (yk === 0) continue;
        for (let p = this.Up[k]; p < end; p++) y[this.Ui[p]] -= this.Ux[p] * yk;
      }
      // Undo the column permutation.
      if (perm) {
        x.set(y);
        for (let k = 0; k < n; k++) b[perm[k]] = x[k];
      }
      return b;
    }
  }

  /** Euclidean-ish helpers the controllers and error tests share. */
  function fillWeights(w, u, uprev, reltol, abstol) {
    const n = w.length;
    const scalarAtol = typeof abstol === 'number';
    for (let i = 0; i < n; i++) {
      const a = scalarAtol ? abstol : abstol[i];
      w[i] = a + reltol * Math.max(Math.abs(u[i]), Math.abs(uprev[i]));
    }
    return w;
  }

  /** The internal norm SciML uses by default: root-mean-square, not maximum. */
  function wrmsNorm(e, w) {
    const n = e.length;
    let s = 0;
    for (let i = 0; i < n; i++) {
      const r = e[i] / w[i];
      s += r * r;
    }
    return Math.sqrt(s / n);
  }

  /**
   * The maximum-norm alternative: the worst-scaled component decides. A component
   * that is not a number makes the norm not a number, as it does the rms norm.
   */
  function wmaxNorm(e, w) {
    const n = e.length;
    let m = 0;
    for (let i = 0; i < n; i++) {
      const r = Math.abs(e[i] / w[i]);
      if (r > m) m = r;
      else if (r !== r) return NaN;
    }
    return m;
  }

  /* ---------- core/jacobian.js ---------- */
  /* ==========================================================================
     ode_julia / core / jacobian

     Getting df/du, and turning it into the matrix the solvers actually invert.

     Two things live here.

     1. JacobianCache -- produces J, either by calling a Jacobian the caller
        supplied or by differencing f. Differencing costs one evaluation of the
        whole right-hand side per *group* of structurally orthogonal columns, not
        per column, so a sparsity pattern is worth giving even when the matrix is
        then handled densely: a chemical Jacobian of 63 species needs about 45
        groups, and one of 200 species often still needs fewer than 50.

     2. WFactorization -- forms W = I − γh·J (or I/(γh) − J, which Radau and the
        Rosenbrock methods want) and factorises it, dense or sparse, and knows
        when it may skip doing so. That last part is where the time goes: a stiff
        solver that re-forms and re-factorises W on every step of a smooth
        stretch does several times the work of one that does not.
     ========================================================================== */


  const SQRT_EPS = Math.sqrt(Number.EPSILON);   // ~1.49e-8

  /**
   * Group the columns of a sparsity pattern so that no two columns in a group
   * share a row.
   *
   * Greedy distance-1 colouring of the column-intersection graph, largest degree
   * first. Perturbing every column of a group at once and differencing gives
   * each of their columns exactly, because no row receives a contribution from
   * more than one of them.
   *
   * @param {number} n
   * @param {Int32Array} colPtr
   * @param {Int32Array} rowIdx
   * @returns {{colour: Int32Array, groups: Int32Array[], count: number}}
   */
  function colourColumns(n, colPtr, rowIdx) {
    // rows -> the columns that touch them, so two columns can be seen to clash.
    const rowCount = new Int32Array(n + 1);
    for (let j = 0; j < n; j++) {
      for (let k = colPtr[j]; k < colPtr[j + 1]; k++) rowCount[rowIdx[k] + 1]++;
    }
    for (let i = 0; i < n; i++) rowCount[i + 1] += rowCount[i];
    const rowCols = new Int32Array(rowCount[n]);
    const at = Int32Array.from(rowCount);
    for (let j = 0; j < n; j++) {
      for (let k = colPtr[j]; k < colPtr[j + 1]; k++) rowCols[at[rowIdx[k]]++] = j;
    }

    const order = Array.from({ length: n }, (_, j) => j)
      .sort((a, b) => (colPtr[b + 1] - colPtr[b]) - (colPtr[a + 1] - colPtr[a]));

    const colour = new Int32Array(n).fill(-1);
    const taken = new Uint8Array(n + 1);
    let count = 0;
    const touched = [];
    for (const j of order) {
      touched.length = 0;
      for (let k = colPtr[j]; k < colPtr[j + 1]; k++) {
        const i = rowIdx[k];
        for (let p = rowCount[i]; p < rowCount[i + 1]; p++) {
          const other = rowCols[p];
          const c = colour[other];
          if (c >= 0 && !taken[c]) { taken[c] = 1; touched.push(c); }
        }
      }
      let c = 0;
      while (taken[c]) c++;
      colour[j] = c;
      if (c + 1 > count) count = c + 1;
      for (const t of touched) taken[t] = 0;
    }

    const sizes = new Int32Array(count);
    for (let j = 0; j < n; j++) sizes[colour[j]]++;
    const groups = Array.from({ length: count }, (_, c) => new Int32Array(sizes[c]));
    const fillAt = new Int32Array(count);
    for (let j = 0; j < n; j++) {
      const c = colour[j];
      groups[c][fillAt[c]++] = j;
    }
    return { colour, groups, count };
  }

  /** A dense n×n pattern, for when the caller gives none. */
  function densePattern(n) {
    const colPtr = new Int32Array(n + 1);
    const rowIdx = new Int32Array(n * n);
    for (let j = 0; j < n; j++) {
      colPtr[j + 1] = (j + 1) * n;
      for (let i = 0; i < n; i++) rowIdx[j * n + i] = i;
    }
    return { colPtr, rowIdx };
  }

  /**
   * Produces J = df/du at (t, u).
   *
   * Three ways in, in order of preference:
   *   jac(t, u, J)      the caller fills J themselves -- exact, and cheapest
   *   jacPattern + f    differenced, one f per colour group
   *   f alone           differenced, one f per column (n+1 evaluations a time)
   */
  class JacobianCache {
    /**
     * @param {number} n
     * @param {object} opts
     * @param {(t:number,u:Float64Array,J:object)=>void} [opts.jac]  fills J in place
     * @param {{colPtr:Int32Array,rowIdx:Int32Array}} [opts.jacPattern]
     * @param {'auto'|'refactor'|'sparse'|'dense'} [opts.matrix]  'refactor' is the sparse LU here
     * @param {boolean} [opts.central]  central differences (2 f per group, one more digit)
     */
    constructor(n, opts = {}) {
      this.n = n;
      this.userJac = opts.jac || null;
      this.central = !!opts.central;
      this.pattern = opts.jacPattern || null;
      this.sparse = false;
      this.nf = 0;         // f evaluations spent on Jacobians
      this.njac = 0;

      // Which storage J lives in. Sparse only pays when the pattern is given and
      // genuinely sparse; the factorisation decides separately, since a sparse J
      // can still have a factor so full that a dense LU is faster.
      // 'refactor' asks for the LU that keeps its pivots, which is the NDF's
      // (../../core/refactor.js); this package has none, and its sparse LU is
      // the nearest thing to it.
      const want = opts.matrix || 'auto';
      const nnz = this.pattern ? this.pattern.colPtr[n] : n * n;
      this.sparse = want === 'sparse' || want === 'refactor' || (want === 'auto' && !!this.pattern && nnz < 0.25 * n * n);

      if (!this.pattern && (this.sparse || !this.userJac)) this.pattern = densePattern(n);

      if (this.sparse) {
        this.J = new CSC(n, this.pattern.colPtr, this.pattern.rowIdx);
      } else {
        this.J = DenseMatrix.zeros(n);
      }

      // Differencing machinery. Built even when a `jac` was given, because that
      // callback may answer `false` for a point it will not vouch for -- see
      // `evaluate` -- and differencing that one call is the whole answer to it.
      // A colouring at construction and three vectors is what it costs; for a
      // `jac` given with no pattern, the colouring waits until the callback first
      // declines, since the pattern to difference through is then a dense one --
      // n^2 entries a run that is never declined should not pay for.
      this.diffPattern = this.pattern;
      this.groups = this.pattern ? colourColumns(n, this.pattern.colPtr, this.pattern.rowIdx).groups : null;
      this.upert = new Float64Array(n);
      this.fpert = new Float64Array(n);
      this.fpert2 = this.central ? new Float64Array(n) : null;
      this.delta = new Float64Array(n);
    }

    /** How many right-hand-side evaluations one differenced Jacobian costs. */
    get groupCount() { return this.groups ? this.groups.length : 0; }

    /**
     * Fill this.J with df/du at (t, u). `fu` is f(t, u), already computed by the
     * caller -- forward differencing needs it and recomputing it is a waste.
     *
     * @param {(t:number,u:Float64Array,out:Float64Array)=>void} f
     */
    evaluate(f, t, u, fu) {
      this.njac++;
      // A caller's `jac` may answer `false` to mean "not this time" -- the
      // Ecolego port's analytic matrix declines a point where an entry comes out
      // non-finite, and differences for that one call rather than handing over a
      // matrix with an infinity in it. Anything else, including undefined, is
      // the matrix having been filled.
      if (this.userJac && this.userJac(t, u, this.J) !== false) return this.J;
      if (!this.groups) {
        this.diffPattern = densePattern(this.n);
        this.groups = colourColumns(this.n, this.diffPattern.colPtr, this.diffPattern.rowIdx).groups;
      }
      const { n, groups, upert, fpert, delta } = this;
      const { colPtr, rowIdx } = this.diffPattern;
      const values = this.sparse ? this.J.values : this.J.data;
      if (this.sparse) values.fill(0); else this.J.data.fill(0);

      for (const group of groups) {
        // One perturbation vector for the whole group.
        upert.set(u);
        for (let g = 0; g < group.length; g++) {
          const j = group[g];
          // The step the reference implementations use: relative to the component, but
          // never smaller than the same fraction of 1, so a component sitting at
          // zero still gets differenced.
          const d = SQRT_EPS * Math.max(Math.abs(u[j]), 1e-5);
          delta[j] = d;
          upert[j] = u[j] + d;
        }
        this.nf++;
        f(t, upert, fpert);
        if (this.central) {
          for (let g = 0; g < group.length; g++) {
            const j = group[g];
            upert[j] = u[j] - delta[j];
          }
          this.nf++;
          f(t, upert, this.fpert2);
        }

        for (let g = 0; g < group.length; g++) {
          const j = group[g];
          const scale = this.central ? 1 / (2 * delta[j]) : 1 / delta[j];
          for (let k = colPtr[j]; k < colPtr[j + 1]; k++) {
            const i = rowIdx[k];
            const back = this.central ? this.fpert2[i] : fu[i];
            const v = (fpert[i] - back) * scale;
            if (this.sparse) values[k] = v;
            else this.J.data[j * n + i] = v;
          }
        }
      }
      return this.J;
    }
  }

  /**
   * W = I − γh·J, or W = I/(γh) − J, formed and factorised.
   *
   * `transform` picks between them. The first is what a Newton iteration on a
   * DIRK or BDF stage wants; the second is what the Rosenbrock methods and Radau
   * want, because their stage equations are already written with the increments
   * divided through by γh, and forming W that way keeps the linear system's
   * scaling independent of the step size.
   *
   * The factorisation is kept and reused. `needsUpdate` is the whole economy of
   * a stiff solver: J is re-differenced only when the Newton iteration says it
   * has gone stale, and W is re-factorised only when J changed or γh moved
   * enough to matter.
   */
  class WFactorization {
    /**
     * @param {number} n
     * @param {JacobianCache} jacCache
     * @param {object} [opts]
     * @param {'auto'|'refactor'|'sparse'|'dense'} [opts.matrix]  'refactor' is the sparse LU here
     * @param {boolean} [opts.reorder]  apply a fill-reducing ordering (sparse only)
     */
    constructor(n, jacCache, opts = {}) {
      this.n = n;
      this.jacCache = jacCache;
      this.sparse = jacCache.sparse;
      this.nfactor = 0;
      this.nsolve = 0;
      this.fill = null;
      this.ordering = 'none';

      if (this.sparse) {
        // W has the pattern of J plus a full diagonal, which J may not carry.
        const J = jacCache.J;
        const rows = []; const cols = [];
        for (let j = 0; j < n; j++) {
          for (let k = J.colPtr[j]; k < J.colPtr[j + 1]; k++) { rows.push(J.rowIdx[k]); cols.push(j); }
          rows.push(j); cols.push(j);
        }
        this.W = cscFromTriplets(n, rows, cols);
        // Where each entry of J lands in W, worked out once.
        this.jToW = new Int32Array(J.colPtr[n]);
        for (let j = 0; j < n; j++) {
          for (let k = J.colPtr[j]; k < J.colPtr[j + 1]; k++) {
            const i = J.rowIdx[k];
            let p = this.W.colPtr[j];
            while (this.W.rowIdx[p] !== i) p++;
            this.jToW[k] = p;
          }
        }
        this.diagW = new Int32Array(n);
        for (let j = 0; j < n; j++) {
          let p = this.W.colPtr[j];
          while (this.W.rowIdx[p] !== j) p++;
          this.diagW[j] = p;
        }
        const perm = opts.reorder === false
          ? null
          : reverseCuthillMcKee(n, this.W.colPtr, this.W.rowIdx);
        this.ordering = perm ? 'reverse Cuthill-McKee' : 'natural';
        this.lu = new SparseLU(n, this.W.colPtr, this.W.rowIdx, perm);
      } else {
        this.W = DenseMatrix.zeros(n);
        this.lu = new DenseLU(n);
      }

      // What the stored factorisation was built from.
      this.gammaDt = NaN;
      this.transform = false;
      this.jacT = NaN;
      this.jacStale = true;
      this.haveFactor = false;

      // How many steps the stored Jacobian has been used for, and the most it
      // may be. A stiff solver saves most of its work by reusing J, and the
      // usual rule -- reuse while the Newton iteration keeps converging quickly
      // -- has a hole in it: a Newton seeded close enough to converge on its
      // first iteration always reports fast convergence, so J is never
      // questioned. TRBDF2 on the pollution problem walked off with a Jacobian
      // hundreds of steps old, converged happily at every step to the wrong
      // root, and reached 1e9 in components that belong between 0 and 1. By then
      // the relative error test scales with the blown-up state and notices
      // nothing. So there is also a plain age limit, as CVODE has (MSBP = 20).
      this.age = 0;
      this.maxAge = opts.maxJacAge ?? 20;
    }

    /** Say that J is out of date, so the next form() re-evaluates it. */
    markStale() { this.jacStale = true; }

    /** One accepted step has passed. */
    agePlus() { this.age++; }

    /** Has the stored Jacobian been used for as long as it may be? */
    get tooOld() { return this.age >= this.maxAge; }

    /** Is the stored J the one for this (t, u)? */
    isCurrent(t) { return !this.jacStale && this.jacT === t; }

    /**
     * Ensure J is current, then build and factorise W for this γh.
     *
     * @returns {boolean} false if W is singular, which the caller answers by
     *                    cutting the step rather than by giving up.
     */
    form(f, t, u, fu, gammaDt, transform, forceJac = false) {
      const n = this.n;
      // Only the caller decides. An earlier version also re-evaluated whenever t
      // had moved, which is every step, so the Jacobian reuse that the whole
      // design is built around never happened once: FBDF reported exactly as
      // many Jacobians as accepted steps.
      if (forceJac || this.jacStale || this.tooOld) {
        this.jacCache.evaluate(f, t, u, fu);
        this.jacT = t;
        this.jacStale = false;
        this.age = 0;
        this.haveFactor = false;
      } else if (this.haveFactor && this.gammaDt === gammaDt && this.transform === transform) {
        return true;             // nothing has changed: reuse the factor
      }

      const J = this.jacCache.J;
      if (this.sparse) {
        const w = this.W.values;
        w.fill(0);
        const jv = J.values;
        if (transform) {
          const d = 1 / gammaDt;
          for (let k = 0; k < jv.length; k++) w[this.jToW[k]] = -jv[k];
          for (let j = 0; j < n; j++) w[this.diagW[j]] += d;
        } else {
          for (let k = 0; k < jv.length; k++) w[this.jToW[k]] = -gammaDt * jv[k];
          for (let j = 0; j < n; j++) w[this.diagW[j]] += 1;
        }
        this.nfactor++;
        const ok = this.lu.factor(this.W.colPtr, this.W.rowIdx, w);
        this.fill = this.lu.fill;
        this.haveFactor = ok;
        this.gammaDt = gammaDt;
        this.transform = transform;
        return ok;
      }

      const w = this.W.data;
      const jd = J.data;
      if (transform) {
        const d = 1 / gammaDt;
        for (let k = 0; k < w.length; k++) w[k] = -jd[k];
        for (let j = 0; j < n; j++) w[j * n + j] += d;
      } else {
        for (let k = 0; k < w.length; k++) w[k] = -gammaDt * jd[k];
        for (let j = 0; j < n; j++) w[j * n + j] += 1;
      }
      this.nfactor++;
      const ok = this.lu.factor(this.W);
      this.haveFactor = ok;
      this.gammaDt = gammaDt;
      this.transform = transform;
      return ok;
    }

    /** Solve Wx = b in place. */
    solve(b) {
      this.nsolve++;
      this.lu.solve(b);
      return b;
    }
  }

  /* ---------- core/newton.js ---------- */
  /* ==========================================================================
     ode_julia / core / newton

     The simplified Newton iteration the implicit methods share, with
     OrdinaryDiffEq's convergence machinery.

     "Simplified" means W is held fixed across the iterations of one stage, and
     usually across several steps: re-forming the Jacobian is the expensive part,
     and a Newton iteration on a stiff stage converges perfectly well with a W
     that is merely close. The price is that convergence has to be watched, and
     that watching is most of what is in this file.

     The heuristics -- κ = 1/100, the contraction estimate θ, the forecast
     η = θ/(1−θ), the divergence tests, the carried-over ηold -- are taken
     from OrdinaryDiffEqNonlinearSolve's nlsolve!. They are tuning, arrived at
     over years against the standard stiff test sets, and there is nothing to be
     gained by inventing different ones.

     SIGN AND SCALING CONVENTION. This package builds W in its textbook form:

          W = I − γh·J          (untransformed, what a Newton stage wants, and
                                 what this file assumes -- see `solve`)
          W = I/(γh) − J        (transformed, what Rosenbrock and Radau want)

     OrdinaryDiffEq stores the negative of these -- `W = J - M*inv(dtgamma)`,
     despite what its own docstring says -- so its updates read `z - W\\r` where
     the same step here reads `z + W\\r`. Anyone comparing the two line by line
     should expect exactly one sign to differ at each linear solve.
     ========================================================================== */

  /** How the stage value is recovered from the stage increment z. */
  const DIRK = 'DIRK';                               // u = tmp + γ·z
  const COEFFICIENT_MULTISTEP = 'COEFFICIENT_MULTISTEP'; // u = z

  const Convergence = 'Convergence';
  const Divergence = 'Divergence';
  const NewtonMaxIters = 'MaxIters';   // named apart from the
  // integrator's MaxIters: one says a stage would not converge, the other
  // says the whole run ran out of steps, and a single-file bundle cannot
  // hold two constants of the same name.
  const Singular = 'Singular';

  /** 100·sqrt(eps): the band around θ = 1 where floating point has run out. */
  const EPS_AROUND_ONE = 100 * Math.sqrt(Number.EPSILON);

  /**
   * How closely each stage's Newton iteration must converge, as a fraction of
   * one unit of the integration tolerance.
   *
   * OrdinaryDiffEq uses 1/100. This package uses 1/1000, and the difference is
   * measured rather than chosen: at 1/100 the stages of an ESDIRK method carry
   * enough left-over Newton error to contaminate its embedded error estimate,
   * which is a small difference of those same stages and so does not enjoy the
   * cancellation the solution does. The symptom is not an inaccurate answer --
   * it is a step-size controller acting on a corrupted estimate, which on the
   * pollution problem walked TRBDF2's solution up to 1e9 in components that
   * belong between 0 and 1, and on van der Pol left KenCarp4 twenty thousand
   * tolerance units out. At 1/1000 both are correct and, because the controller
   * is no longer being lied to, both are also several times CHEAPER: TRBDF2 on
   * the pollution problem goes from failing after 876 steps to finishing in 325.
   */
  const DEFAULT_KAPPA = 1e-3;

  /**
   * Scaled residual, as SciML's calculate_residuals: each component of the
   * increment measured against what a unit of error would be for that component.
   * A component that is not a number makes it not a number, in either norm: the
   * maximum used to skip one (`r > m` is never true of NaN), so an iterate with
   * a NaN in it could be declared converged on its other components.
   */
  function residualNorm(dz, uprev, ustep, abstol, reltol, n, norm) {
    const scalarAtol = typeof abstol === 'number';
    if (norm === 'max') {
      let m = 0;
      for (let i = 0; i < n; i++) {
        const a = scalarAtol ? abstol : abstol[i];
        const w = a + reltol * Math.max(Math.abs(uprev[i]), Math.abs(ustep[i]));
        const r = Math.abs(dz[i]) / w;
        if (r > m) m = r;
        else if (r !== r) return NaN;
      }
      return m;
    }
    let s = 0;
    for (let i = 0; i < n; i++) {
      const a = scalarAtol ? abstol : abstol[i];
      const w = a + reltol * Math.max(Math.abs(uprev[i]), Math.abs(ustep[i]));
      const r = dz[i] / w;
      s += r * r;
    }
    return Math.sqrt(s / n);
  }

  /**
   * One reusable simplified-Newton solver.
   *
   * Solves, for the stage increment z,
   *
   *     z = h·f(t + c·h, tmp + γ·z)            (DIRK)
   *     z = tmp + h·γ·f(t + c·h, z)            (COEFFICIENT_MULTISTEP, rearranged
   *                                             so that z is the stage *value*)
   *
   * The caller sets `tmp`, `gamma`, `c` and the method before each solve, and
   * reads `z` afterwards. Nothing is allocated per solve.
   */
  class NewtonSolver {
    /**
     * @param {number} n
     * @param {object} opts
     * @param {number} [opts.kappa=0.01]
     * @param {number} [opts.maxIters=10]
     * @param {number} [opts.fastConvergenceCutoff=0.2]
     * @param {'rms'|'max'} [opts.norm='rms']
     */
    constructor(n, opts = {}) {
      this.n = n;
      this.kappa = opts.kappa ?? DEFAULT_KAPPA;
      this.maxIters = opts.maxIters ?? 10;
      this.fastConvergenceCutoff = opts.fastConvergenceCutoff ?? 0.2;
      this.norm = opts.norm || 'rms';

      this.z = new Float64Array(n);       // the stage increment being solved for
      this.tmp = new Float64Array(n);     // the explicit part, set by the caller
      this.ustep = new Float64Array(n);   // the stage value the residual was taken at
      this.k = new Float64Array(n);       // f at the stage value
      this.dz = new Float64Array(n);      // the Newton correction

      this.gamma = 1;
      this.c = 0;
      this.method = DIRK;

      // Carried between solves, as in OrdinaryDiffEq: the convergence estimate
      // from the previous stage is the best guess for the next one.
      this.etaOld = 1;
      this.prevTheta = 1;
      this.status = Convergence;
      this.iter = 0;
      this.eta = 1;
      this.ndz = 0;
      this.nfails = 0;
      this.nf = 0;

      // Set by the caller for BDF/NDF, where the truncation error is
      // proportional to the total Newton displacement and the convergence test
      // has to be tightened by the same constant.
      this.errorConstant = 1;
    }

    /** Forget the history; used when the integrator restarts. */
    reset() {
      this.etaOld = 1;
      this.prevTheta = 1;
      this.nfails = 0;
    }

    /** The stage value implied by the current z. */
    applyStep(out) {
      const { n, z, tmp, gamma, method } = this;
      if (method === DIRK) for (let i = 0; i < n; i++) out[i] = tmp[i] + gamma * z[i];
      else out.set(z);
      return out;
    }

    /**
     * Run the iteration.
     *
     * @param {(t:number,u:Float64Array,out:Float64Array)=>void} f
     * @param {object} W        a WFactorization, already formed for this γh
     * @param {number} t        the step's start time
     * @param {number} dt
     * @param {Float64Array} uprev
     * @param {object} tol      { reltol, abstol }
     * @param {boolean} [newW]  W was just rebuilt, so ηold should not be trusted
     * @param {boolean} [lastAccepted=true]
     * @returns {string} one of Convergence / Divergence / MaxIters
     */
    solve(f, W, t, dt, uprev, tol, newW, lastAccepted = true) {
      const { n, z, ustep, dz, k, kappa, maxIters } = this;
      const gammaDt = this.gamma * dt;
      const tstep = t + this.c * dt;

      let eta = newW ? Math.max(this.etaOld, Number.EPSILON) ** 0.8 : this.etaOld;
      let ndz = 1;
      let prevTheta = lastAccepted ? this.prevTheta : 1;
      this.status = Divergence;

      for (let iter = 1; iter <= maxIters; iter++) {
        this.iter = iter;
        const ndzPrev = ndz;

        // --- the residual, and the correction that kills it -------------------
        //
        // For a DIRK stage the equation is  g(z) = h·f(tmp + γ·z) − z = 0, so
        // g'(z) = γh·J − I = −W with W = I − γh·J, and one Newton step is
        //
        //     z  ←  z − g'(z)⁻¹·g(z)  =  z + W⁻¹·g(z).
        //
        // W is therefore formed UNTRANSFORMED here, and g is not scaled. The
        // transformed pair -- W = I/(γh) − J against a residual divided by γh,
        // which is how OrdinaryDiffEq writes it -- gives the same increment
        // because the two factors of γh cancel; mixing one with the other does
        // not, and is off by exactly γh. That mistake makes every step fail its
        // error test rather than producing a wrong answer, which is the good
        // kind of mistake, but it is worth saying which convention is in force.
        this.applyStep(ustep);
        this.nf++;
        f(tstep, ustep, k);
        if (this.method === DIRK) {
          for (let i = 0; i < n; i++) dz[i] = dt * k[i] - z[i];
        } else {
          // The stage value is z itself:  g(z) = tmp + γh·f(z) − z.
          for (let i = 0; i < n; i++) dz[i] = this.tmp[i] + gammaDt * k[i] - z[i];
        }
        W.solve(dz);

        ndz = residualNorm(dz, uprev, ustep, tol.abstol, tol.reltol, n, this.norm);
        if (this.errorConstant !== 1) ndz *= this.errorConstant;

        if (!Number.isFinite(ndz)) {
          this.status = Divergence;
          this.nfails++;
          break;
        }

        // --- how fast is it contracting? --------------------------------------
        let theta;
        if (iter > 1) {
          // The 0.3 floor keeps one lucky iteration from declaring victory.
          theta = prevTheta = Math.max(0.3 * prevTheta, ndz / ndzPrev);
          if (Math.abs(theta - 1) <= EPS_AROUND_ONE) {
            // The iteration has stopped moving. Either it is at the root and the
            // remaining motion is rounding, or it is stuck away from it.
            if (ndz <= 1) {
              this.status = Convergence;
              this.nfails = 0;
              for (let i = 0; i < n; i++) z[i] += dz[i];
              this.eta = eta;
              this.ndz = ndz;
              this.etaOld = eta;
              this.prevTheta = prevTheta;
              return this.status;
            }
            this.status = Divergence;
            this.nfails++;
            break;
          }
          if (theta > 2) {
            this.status = Divergence;
            this.nfails++;
            break;
          }
        } else {
          theta = prevTheta;
        }

        // --- take it ----------------------------------------------------------
        for (let i = 0; i < n; i++) z[i] += dz[i];

        // η forecasts the total remaining displacement from the contraction rate:
        // ‖z* − z‖ ≲ θ/(1−θ)·‖dz‖. Converged when that forecast is below κ.
        eta = theta / (1 - theta);
        // The η test may not fire on the first iteration. η is a forecast built
        // from a contraction rate θ, and on iteration 1 there is no θ from this
        // solve to build it from -- the value used is whatever the last solve
        // left behind, which is not evidence about this one. Trusting it lets a
        // single Newton step from a seeded guess declare victory with a
        // correction a fiftieth of a tolerance unit still outstanding. The
        // `ndz < 1e-5` clause is the honest first-iteration case: a correction
        // that small means the guess was already the answer.
        if ((iter === 1 && ndz < 1e-5) || (iter > 1 && eta >= 0 && eta * ndz < kappa)) {
          this.status = Convergence;
          this.nfails = 0;
          break;
        }
        if (iter === maxIters) {
          this.status = NewtonMaxIters;
          this.nfails++;
        }
      }

      this.eta = eta;
      this.ndz = ndz;
      this.etaOld = eta;
      this.prevTheta = prevTheta;
      return this.status;
    }

    /** Did the last solve converge quickly enough to keep W for the next step? */
    get fastConvergence() {
      return this.status === Convergence && this.eta < this.fastConvergenceCutoff;
    }
  }

  /* ---------- core/controller.js ---------- */
  /* ==========================================================================
     ode_julia / core / controller

     Choosing the next step size from the error estimate.

     The PI controller is OrdinaryDiffEq's default for these methods and is what
     is implemented here, with its coefficients:

         β₁ = 7/(10k),  β₂ = 2/(5k)      k the order of the error estimate
         γ  = 9/10,     qmin = 1/5,      qmax = 10
         qoldinit = 1e-4

     The proportional term alone (the I controller, β₂ = 0) is the textbook
     h·(1/EEst)^(1/k). The integral term damps the oscillation that the plain
     version falls into on stiff problems, where one lucky step is followed by
     one that is far too large. Setting `beta2: 0` recovers the I controller,
     which is what the BDF methods use when they change order.
     ========================================================================== */

  /**
   * @param {object} opts
   * @param {number} opts.order      the order of the *error estimate*
   * @param {number} [opts.beta1]
   * @param {number} [opts.beta2]
   * @param {number} [opts.gamma=0.9]      safety factor
   * @param {number} [opts.qmin=0.2]       fastest allowed shrink is dt*qmin
   * @param {number} [opts.qmax=10]        fastest allowed growth is dt*qmax
   * @param {number} [opts.qsteadyMin=1]   inside [min,max] the step is left alone
   * @param {number} [opts.qsteadyMax=1.2]
   * @param {number} [opts.qoldinit=1e-4]
   */
  class PIController {
    constructor(opts) {
      const k = opts.order;
      this.beta1 = opts.beta1 ?? 7 / (10 * k);
      this.beta2 = opts.beta2 ?? 2 / (5 * k);
      this.gamma = opts.gamma ?? 0.9;
      this.qmin = opts.qmin ?? 0.2;
      this.qmax = opts.qmax ?? 10;
      this.qsteadyMin = opts.qsteadyMin ?? 1;
      this.qsteadyMax = opts.qsteadyMax ?? 1.2;
      this.qoldinit = opts.qoldinit ?? 1e-4;
      this.errold = this.qoldinit;
      this.q11 = 1;
    }

    /** Order changed under us (the BDF methods do this); refit the exponents. */
    setOrder(k) {
      this.beta1 = 7 / (10 * k);
      this.beta2 = 2 / (5 * k);
    }

    /**
     * q, the factor the step is *divided* by: dtnew = dt / q.
     * @param {number} EEst  the scaled error estimate; <= 1 is an accepted step
     */
    q(EEst) {
      if (EEst === 0) return 1 / this.qmax;
      this.q11 = EEst ** this.beta1;
      let q = this.q11 / this.errold ** this.beta2;
      q /= this.gamma;
      return Math.min(1 / this.qmin, Math.max(1 / this.qmax, q));
    }

    /** dtnew after an accepted step, and the state update that goes with it. */
    accept(EEst, dt) {
      let q = this.q(EEst);
      if (q >= this.qsteadyMin && q <= this.qsteadyMax) q = 1;
      this.errold = Math.max(EEst, this.qoldinit);
      return dt / q;
    }

    /**
     * dtnew after a rejected step. The proportional part only: the integral term
     * remembers accepted steps, and a rejected one says nothing about the trend.
     *
     * EEst has to be passed in. Reading the q11 left over from the last accepted
     * step instead -- which is what this did at first, and what it looks like
     * OrdinaryDiffEq does until you notice it recomputes the controller on every
     * step, accepted or not -- makes the shrink factor a number about a step
     * that already succeeded. It is then always close to 1, the step comes down
     * by a tenth at a time, and a solver meeting a sharp transition takes tens
     * of thousands of rejections to get through it instead of five.
     */
    reject(EEst, dt) {
      this.q11 = EEst ** this.beta1;
      return dt / Math.min(1 / this.qmin, this.q11 / this.gamma);
    }

    reset() {
      this.errold = this.qoldinit;
      this.q11 = 1;
    }
  }

  /**
   * Hairer's starting step (Solving ODEs I, II.4), which is what SciML uses.
   *
   * Two explicit Euler probes: the first sizes h from ‖u₀‖/‖f₀‖, the second
   * refines it from the observed second derivative. Cheap -- two extra f calls --
   * and much better than any fixed guess, which on a stiff problem is either
   * thrown away in a dozen rejections or starts so small the first decade of the
   * solution is wasted.
   *
   * @returns {number} a signed step, in the direction of tdir
   */
  function initialStep(f, t0, u0, f0, tdir, order, reltol, abstol, dtmax, work) {
    const n = u0.length;
    const { u1, f1, w } = work;
    const scalarAtol = typeof abstol === 'number';
    for (let i = 0; i < n; i++) w[i] = (scalarAtol ? abstol : abstol[i]) + reltol * Math.abs(u0[i]);

    let d0 = 0;
    let d1 = 0;
    for (let i = 0; i < n; i++) {
      const a = u0[i] / w[i];
      const b = f0[i] / w[i];
      d0 += a * a;
      d1 += b * b;
    }
    d0 = Math.sqrt(d0 / n);
    d1 = Math.sqrt(d1 / n);

    let h0 = (d0 < 1e-5 || d1 < 1e-5) ? 1e-6 : 0.01 * (d0 / d1);
    h0 = Math.min(h0, Math.abs(dtmax));

    for (let i = 0; i < n; i++) u1[i] = u0[i] + tdir * h0 * f0[i];
    f(t0 + tdir * h0, u1, f1);

    let d2 = 0;
    for (let i = 0; i < n; i++) {
      const a = (f1[i] - f0[i]) / w[i];
      d2 += a * a;
    }
    d2 = Math.sqrt(d2 / n) / h0;

    const dmax = Math.max(d1, d2);
    const h1 = dmax <= 1e-15
      ? Math.max(1e-6, h0 * 1e-3)
      : (0.01 / dmax) ** (1 / (order + 1));

    const h = Math.min(100 * h0, h1, Math.abs(dtmax));
    return tdir * h;
  }

