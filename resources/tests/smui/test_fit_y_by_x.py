def hyp3f2(a1, a2, a3, b1, b2, z):
    s_, term_ = 1.0, 1.0
    for kk in range(100000):
        term_ *= (a1 + kk) * (a2 + kk) * (a3 + kk) / ((b1 + kk) * (b2 + kk) * (kk + 1)) * z
        s_ += term_
        if abs(term_) < 1e-17 * abs(s_):
            break
    return s_


