#!/usr/bin/env python3
"""Emit Pianoskolan's icon (piano.html): resources/images/piano-icon.svg, and
from it piano-icon-32.png (the fallback) and piano-icon-180.png (the touch
icon, which an iPhone puts on its home screen, from Safari or from Chrome).

    python3 scripts/gen-piano-icon.py            # the SVG and the two PNGs
    python3 scripts/gen-piano-icon.py --svg-only

The drawing is two eighth notes on one beam, in the kvot mark's isometric
language (scripts/kvot_icon.py); the SVG's own comment says why. Edit the
inputs below, never the numbers in the SVG.

Nothing is written unless every edge is horizontal, vertical or at 30 degrees;
the drawing fits the square; the gap between the two notes and the hole under
the beam are each more than a pixel at sixteen pixels; and every face is drawn
after the faces it hides.
"""
import sys

import kvot_icon as K

OUT = K.ROOT / 'resources/images/piano-icon.svg'
PNG32 = K.ROOT / 'resources/images/piano-icon-32.png'
PNG180 = K.ROOT / 'resources/images/piano-icon-180.png'

# The inputs, in world units: the drawing is scaled to the square afterwards.
HEAD = 14           # a notehead, along the notes' plane
HEAD_H = 10         # and its height: large heads, or at tab size the notes are a gate on two feet
STEM = 4.5          # a stem's width
APART = 27          # the second note, from the first
HEIGHT = 37         # the top of the beam, from the foot of the heads
BEAM = 7.5          # the beam's thickness
DEPTH = 6.5         # the notes' depth, as it shows on screen

COMMENT = f'''\t<!--
\t\tTwo eighth notes on one beam: a melody, which is what Pianoskolan
\t\tteaches, a note at a time, and what it listens for.

{K.RULES}

\t\tThe notes are their outline in one upright plane, extruded towards
\t\tthe viewer: two square heads, a stem rising from the right of each,
\t\tand the beam across their tops. The plane runs to the right and back,
\t\tso the heads lean as printed noteheads do and the beam rises to the
\t\tright, as it does over two notes going up.

\t\tA keyboard was drawn first and dropped: in this projection every top
\t\tis lit, so the black keys show as light as the white ones, and at tab
\t\tsize the keys were a stepped slab.

\t\tGenerated by scripts/gen-piano-icon.py, not typed. Change the inputs
\t\tthere and run it again rather than editing the numbers here.
\t-->
'''


def outline():
    """The two notes in their plane: (along it, up), anticlockwise from the
    foot of the first head."""
    left, right = HEAD - STEM, APART + HEAD - STEM
    return [(0, 0), (HEAD, 0), (HEAD, HEIGHT - BEAM), (right, HEIGHT - BEAM), (right, HEAD_H),
            (APART, HEAD_H), (APART, 0), (APART + HEAD, 0), (APART + HEAD, HEIGHT), (left, HEIGHT),
            (left, HEAD_H), (0, HEAD_H)]


def main():
    faces, _ = K.order([K.upright(outline(), 0, DEPTH / K.S)])
    placed, k = K.place(faces)
    errors = K.problems(placed)
    # A unit of the square is a quarter of a pixel at sixteen pixels. Between
    # the first stem and the second note shows what is left of their distance
    # once the second note's shaded side has taken its depth; under the beam,
    # what the second head's lit top leaves of the hole.
    gap = ((APART - HEAD) * K.S - DEPTH) * k
    if gap < K.SIZE / 16:
        errors.append(f'the notes are {gap / 4:.2f} px apart at 16 px, under a pixel')
    hole = (HEIGHT - BEAM - HEAD_H - DEPTH / (2 * K.S)) * k
    if hole < K.SIZE / 16:
        errors.append(f'the hole under the beam is {hole / 4:.2f} px high at 16 px, under a pixel')
    if errors:
        sys.exit('not written:\n  ' + '\n  '.join(errors))
    # Each tone in at least half the share measured when the icon was drawn.
    K.write(OUT, PNG32, PNG180, K.svg(placed, 'Pianoskolan', COMMENT, (('the notes', len(placed)),)),
            {K.TOP: 0.018, K.RIGHT: 0.025},
            {K.TOP: 0.018, K.RIGHT: 0.034, K.LEFT: 0.023})


if __name__ == '__main__':
    main()
