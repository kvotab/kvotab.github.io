#!/usr/bin/env node
/*
  Bundle the ode_julia ES modules into one classic script.

      node scripts/build-ode-julia.mjs

  The package is written as ES modules, which is what it should be. A page that
  also has to run with no Web Worker at all -- facsimile.html does, for a
  file:// visit -- needs a plain script it can drop in a <script> tag, so this
  concatenates the modules in dependency order, strips the import and export
  keywords, and wraps the result in the same UMD preamble the rest of the site
  uses. Nothing is minified and nothing is rewritten: the bundle is the sources
  with two kinds of line removed, so a stack trace from it still reads.

  It refuses to write if two modules declare the same top-level name, which a
  concatenating bundler would otherwise merge into a syntax error or, worse, a
  silent redefinition.
*/
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'resources/js/ode_julia');
const OUT = join(ROOT, 'resources/js/ode-julia.js');

// Dependency order. Checked below: a module may only use names already defined.
const FILES = [
  'core/linalg.js',
  'core/jacobian.js',
  'core/newton.js',
  'core/controller.js',
  'core/integrator.js',
  'solvers/rodas5p-tableau.js',
  'solvers/rosenbrock.js',
  'solvers/esdirk-tableaus.js',
  'solvers/esdirk.js',
  'solvers/fbdf.js',
  'solvers/qndf.js',
  'solvers/radau-tableau.js',
  'solvers/radau.js',
];

// What the bundle puts on the global. Kept in step with index.js by the check
// at the end, which fails if index.js exports a name this list does not.
const EXPORTS = [
  'ODEProblem', 'ODESolution', 'ODEError', 'solve',
  'Success', 'MaxIters', 'DtLessThanMin', 'Unstable', 'Terminated',
  'DenseMatrix', 'CSC', 'cscFromTriplets', 'DenseLU', 'ComplexDenseLU', 'SparseLU',
  'reverseCuthillMcKee',
  'JacobianCache', 'WFactorization', 'colourColumns', 'densePattern',
  'NewtonSolver', 'PIController', 'initialStep',
  'Rodas5P', 'rosenbrockAlgorithm', 'Rodas5PTableau',
  'TRBDF2', 'KenCarp4', 'esdirkAlgorithm', 'TRBDF2Tableau', 'KenCarp4Tableau',
  'FBDF', 'fornbergWeights',
  'QNDF', 'QBDF', 'rescaleMatrix',
  'RadauIIA5', 'RadauIIA5Tableau',
];

const IMPORT_RE = /^import\s[\s\S]*?from\s+'[^']+';\s*$/gm;
const TOPLEVEL_RE = /^export\s+(?:default\s+)?(class|function|const|let|var)\s+([A-Za-z_$][\w$]*)/gm;
const PLAIN_TOPLEVEL_RE = /^(?:class|function|const|let|var)\s+([A-Za-z_$][\w$]*)/gm;

const seen = new Map();
const chunks = [];
for (const rel of FILES) {
  const raw = readFileSync(join(SRC, rel), 'utf8');
  for (const m of raw.matchAll(TOPLEVEL_RE)) register(m[2], rel);
  for (const m of raw.matchAll(PLAIN_TOPLEVEL_RE)) register(m[1], rel);
  let body = raw.replace(IMPORT_RE, '');
  // `export class X` -> `class X`; a bare `export { ... };` line disappears.
  body = body.replace(/^export\s+(?=(class|function|const|let|var)\s)/gm, '');
  body = body.replace(/^export\s*\{[^}]*\}\s*;?\s*$/gm, '');
  chunks.push(`/* ---------- ${rel} ---------- */\n${body.trim()}\n`);
}

function register(name, rel) {
  if (seen.has(name) && seen.get(name) !== rel) {
    console.error(`duplicate top-level name "${name}" in ${rel} and ${seen.get(name)}`);
    process.exit(1);
  }
  seen.set(name, rel);
}

// Everything index.js exports must be reachable and must be in EXPORTS.
const index = readFileSync(join(SRC, 'index.js'), 'utf8');
const exported = new Set();
for (const m of index.matchAll(/^export\s*\{([^}]*)\}/gm)) {
  for (const raw of m[1].split(',')) {
    const name = raw.trim().split(/\s+as\s+/).pop().trim();
    if (name) exported.add(name);
  }
}
let bad = 0;
for (const name of exported) {
  if (!EXPORTS.includes(name)) { console.error(`index.js exports ${name}, the bundle does not`); bad++; }
  if (!seen.has(name)) { console.error(`index.js exports ${name}, no module declares it`); bad++; }
}
for (const name of EXPORTS) {
  if (!seen.has(name)) { console.error(`the bundle exports ${name}, no module declares it`); bad++; }
}
if (bad) process.exit(1);

const header = `/* ==========================================================================
   ode_julia -- a single-file build

   GENERATED by scripts/build-ode-julia.mjs from resources/js/ode_julia/.
   Do not edit: edit the modules and run the script.

   Stiff ODE solvers ported from DifferentialEquations.jl -- FBDF, Rodas5P,
   KenCarp4, TRBDF2 and RadauIIA5 -- with their linear algebra, Jacobian
   handling, Newton iteration and step-size control. No dependencies.

     const { solve, ODEProblem, FBDF } = OdeJulia;
     const sol = solve(new ODEProblem(f, u0, [0, 1e5], { jac }), FBDF(),
                       { reltol: 1e-8, abstol: 1e-12 });

   The modules under resources/js/ode_julia/ are the source of truth and are
   what to read; see its README.md. This file exists because a page that must
   also work with no Web Worker cannot use ES modules for everything.
   ========================================================================== */
(function (root, factory) {
  const api = factory();
  root.OdeJulia = api;
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
}(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

`;
const footer = `
  return { ${EXPORTS.join(', ')} };
}));
`;
const body = chunks.join('\n').split('\n').map((l) => (l ? `  ${l}` : l)).join('\n');
writeFileSync(OUT, header + body + footer);
console.log(`wrote ${OUT} (${(header + body + footer).length} bytes, ${FILES.length} modules, ${EXPORTS.length} exports)`);
