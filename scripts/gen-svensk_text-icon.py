#!/usr/bin/env python3
"""Emit Svensk text's icon (svensk_text.html): resources/images/
svensk_text-icon.svg, and from it svensk_text-icon-32.png (the fallback) and
svensk_text-icon-180.png (the touch icon, for an iPhone's home screen).

    python3 scripts/gen-svensk_text-icon.py            # the SVG and the two PNGs
    python3 scripts/gen-svensk_text-icon.py --svg-only

The drawing is the two lines of a subtitle, in the kvot mark's isometric
language (scripts/kvot_icon.py); the SVG's own comment says why. Edit the
inputs below, never the numbers in the SVG.

Nothing is written unless every edge is horizontal, vertical or at 30 degrees;
the drawing fits the square; and every face is drawn after the faces it hides.
"""
import sys

import kvot_icon as K

OUT = K.ROOT / 'resources/images/svensk_text-icon.svg'
PNG32 = K.ROOT / 'resources/images/svensk_text-icon-32.png'
PNG180 = K.ROOT / 'resources/images/svensk_text-icon-180.png'

# The inputs, in world units: the drawing is scaled to the square afterwards.
LOWER = 34          # the lower line, end to end
UPPER = 22          # the upper line, shorter: a subtitle broken bottom-heavy
LINE = 6            # a line's height
GAP = 5             # between the lines, enough to stay two lines at sixteen pixels
DEPTH = 4           # its depth, as it shows on screen

COMMENT = f'''\t<!--
\t\tTwo lines of a subtitle: the most a subtitle may have, the upper one the
\t\tshorter, as Swedish subtitling breaks them.

{K.RULES}

\t\tEach line is a bar in one upright plane, extruded towards the viewer,
\t\tso its face is the right-hand tone and its top and left edges show in
\t\tthe other two, as the letters of the other icons do. The upper bar is
\t\tcentred over the lower one.

\t\tGenerated by scripts/gen-svensk_text-icon.py, not typed. Change the
\t\tinputs there and run it again rather than editing the numbers here.
\t-->
'''


def bar(u0, u1, z0, z1):
    return [(u0, z0), (u1, z0), (u1, z1), (u0, z1)]


def main():
    lower = K.upright(bar(0, LOWER, 0, LINE), 0, DEPTH / K.S)
    left = (LOWER - UPPER) / 2
    upper = K.upright(bar(left, left + UPPER, LINE + GAP, 2 * LINE + GAP), 0, DEPTH / K.S)
    faces, _ = K.order([lower, upper])
    placed, _ = K.place(faces)
    errors = K.problems(placed)
    if errors:
        sys.exit('not written:\n  ' + '\n  '.join(errors))
    # Each tone in at least half the share measured when the icon was drawn.
    K.write(OUT, PNG32, PNG180, K.svg(placed, 'Svensk text', COMMENT, (('the two lines', len(placed)),)),
            {K.TOP: 0.048, K.RIGHT: 0.074}, {K.TOP: 0.043, K.RIGHT: 0.056, K.LEFT: 0.009})


if __name__ == '__main__':
    main()
