#!/usr/bin/env python3
"""Emit the reactive-transport page's icon (rtm.html): resources/images/
rtm-icon.svg, and from it rtm-icon-32.png (the fallback) and rtm-icon-180.png
(the touch icon, for an iPhone's home screen).

    python3 scripts/gen-rtm-icon.py            # the SVG and the two PNGs
    python3 scripts/gen-rtm-icon.py --svg-only

The drawing is a column with a dissolution front, in the kvot mark's
isometric language (scripts/kvot_icon.py); the SVG's own comment says why.
Edit the inputs below, never the numbers in the SVG.

Nothing is written unless every edge is horizontal, vertical or at 30 degrees;
the drawing fits the square; the bare column behind the front and the front
itself are each more than a pixel at sixteen pixels; and every face is drawn
after the faces it hides.
"""
import sys

import kvot_icon as K

OUT = K.ROOT / 'resources/images/rtm-icon.svg'
PNG32 = K.ROOT / 'resources/images/rtm-icon-32.png'
PNG180 = K.ROOT / 'resources/images/rtm-icon-180.png'

# The inputs, in world units: the drawing is scaled to the square afterwards.
LENGTH = 30         # the column, from the inlet to the outlet
FRONT = 13          # how far the front has come from the inlet
FULL = 10           # the column's height where it still holds the mineral
BARE = 3            # its height behind the front, the mineral dissolved
WIDTH = 7           # the column's width

COMMENT = f'''\t<!--
\t\tA column through which water has flowed and dissolved the mineral it
\t\theld, from the inlet up to a front: behind the front the column is
\t\tbare and low, ahead of it the mineral is still there. The front, the
\t\tshaded riser between the two, is what the page is about: where a
\t\treaction has got to, carried along by the water.

{K.RULES}

\t\tThe column is its outline in the upright plane along its length,
\t\textruded across its width: the inlet nearest the viewer on the left,
\t\tthe outlet rising to the right, as the flow runs on the page's charts.

\t\tGenerated by scripts/gen-rtm-icon.py, not typed. Change the inputs
\t\tthere and run it again rather than editing the numbers here.
\t-->
'''


def outline():
    """The column along its length (u) and height (z): bare behind the front, full ahead of it."""
    return [(0, 0), (LENGTH, 0), (LENGTH, FULL), (FRONT, FULL), (FRONT, BARE), (0, BARE)]


def main():
    faces, _ = K.order([K.upright(outline(), 0, WIDTH)])
    placed, k = K.place(faces)
    errors = K.problems(placed)
    # On screen a height is one unit for one; at sixteen pixels a unit of the square is a quarter of a pixel.
    if BARE * k < K.SIZE / 16:
        errors.append(f'the bare column is {BARE * k / 4:.2f} px high at 16 px, under a pixel')
    if (FULL - BARE) * k < K.SIZE / 16:
        errors.append(f'the front is {(FULL - BARE) * k / 4:.2f} px high at 16 px, under a pixel')
    if errors:
        sys.exit('not written:\n  ' + '\n  '.join(errors))
    # Each tone in at least half the share measured when the icon was drawn.
    K.write(OUT, PNG32, PNG180, K.svg(placed, 'Reactive Transport', COMMENT, (('the column', len(placed)),)),
            {K.TOP: 0.049, K.RIGHT: 0.051}, {K.TOP: 0.039, K.RIGHT: 0.039, K.LEFT: 0.013})


if __name__ == '__main__':
    main()
