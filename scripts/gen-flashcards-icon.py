#!/usr/bin/env python3
"""Emit Glosor's icon (flashcards.html): resources/images/flashcards-icon.svg,
and from it flashcards-icon-32.png (the fallback) and flashcards-icon-180.png
(the touch icon, which an iPhone puts on its home screen).

    python3 scripts/gen-flashcards-icon.py            # the SVG and the two PNGs
    python3 scripts/gen-flashcards-icon.py --svg-only

The drawing is a pile of three word cards, the top one with three lines of
writing, in the kvot mark's isometric language (scripts/kvot_icon.py); the
SVG's own comment says why it looks the way it does. Edit the inputs below,
never the numbers in the SVG: they are this arithmetic, scaled to the square
and rounded.

Nothing is written unless every edge is horizontal, vertical or at 30 degrees;
the drawing fits the square; the lines of writing are a pixel apart at
thirty-two pixels; and every face is drawn after the faces it hides.
"""
import sys

import kvot_icon as K

OUT = K.ROOT / 'resources/images/flashcards-icon.svg'
PNG32 = K.ROOT / 'resources/images/flashcards-icon-32.png'
PNG180 = K.ROOT / 'resources/images/flashcards-icon-180.png'

# The inputs, in world units: the drawing is scaled to the square afterwards.
WIDTH = 24          # a card along x
LENGTH = 32         # a card along u: a card three to four in proportion
THICK = 4.4         # a card's thickness: enough to hold its own beside the other pages' blocks
CARDS = [(0, 2.6), (2.2, 0), (1.1, 1.3)]   # each card's (x, u), from the bottom up: a slightly untidy pile
BAR = 3.2           # a line of writing, across x
RAISE = 3.0         # and how high it stands on the card
MARGIN = 4.2        # the card's margin around the writing
LINES = [0.55, 0.9, 0.7]   # each line's length, of what the margins leave

COMMENT = f'''\t<!--
\t\tA pile of three word cards, the top one with three lines of writing:
\t\tGlosor's cards, with this week's words on them.

{K.RULES}

\t\tEach card is a box, a little out of line with the one under it so
\t\tthat the pile shows as cards, not as one block. The lines of writing
\t\tare low bars on the top card: their tops are lit like the card, so
\t\twhat shows of them is their two dark faces, as strokes. They are a
\t\tpixel apart at thirty-two pixels; at sixteen, the pile is a light
\t\ttile with dark edges, which is all a tab has room for.

\t\tGenerated by scripts/gen-flashcards-icon.py, not typed. Change the
\t\tinputs there and run it again rather than editing the numbers here.
\t-->
'''


def shapes():
    cards = [K.box(dx, dx + WIDTH, du, du + LENGTH, i * THICK, (i + 1) * THICK) for i, (dx, du) in enumerate(CARDS)]
    tx, tu = CARDS[-1]
    z = len(CARDS) * THICK
    step = (WIDTH - 2 * MARGIN) / len(LINES)
    lines = []
    for r, share in enumerate(LINES):
        x0 = tx + MARGIN + r * step
        lines.append(K.box(x0, x0 + BAR, tu + MARGIN, tu + MARGIN + share * (LENGTH - 2 * MARGIN), z, z + RAISE))
    return cards + lines


def main():
    faces, seq = K.order(shapes())
    placed, k = K.place(faces)
    errors = K.problems(placed)
    if seq != sorted(seq):
        errors.append(f'the cards and lines are not drawn bottom up and back to front: {seq}')
    gap = ((WIDTH - 2 * MARGIN) / len(LINES) - BAR) * K.S * k
    if gap < 2:
        errors.append(f'the lines of writing are {gap / 2:.2f} px apart at 32 px, under a pixel')
    if errors:
        sys.exit('not written:\n  ' + '\n  '.join(errors))
    text = K.svg(placed, 'Glosor', COMMENT,
                 (('the cards, from the bottom up', 3 * len(CARDS)), ('the lines of writing on the top card', 3 * len(LINES))))
    # Each tone in at least half the share measured when the icon was drawn.
    K.write(OUT, PNG32, PNG180, text, {K.TOP: 0.06, K.RIGHT: 0.03}, {K.TOP: 0.05, K.RIGHT: 0.03, K.LEFT: 0.02})


if __name__ == '__main__':
    main()
