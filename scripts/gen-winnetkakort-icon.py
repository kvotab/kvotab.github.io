#!/usr/bin/env python3
"""Emit Winnetkakort's icon (winnetkakort.html): resources/images/
winnetkakort-icon.svg, and from it winnetkakort-icon-32.png (the fallback)
and winnetkakort-icon-180.png (the touch icon, for an iPhone's home screen).

    python3 scripts/gen-winnetkakort-icon.py            # the SVG and the two PNGs
    python3 scripts/gen-winnetkakort-icon.py --svg-only

The drawing is a plus sign, a solid block, in the kvot mark's isometric
language (scripts/kvot_icon.py); the SVG's own comment says why. Edit the
inputs below, never the numbers in the SVG.

Nothing is written unless every edge is horizontal, vertical or at 30 degrees;
the drawing fits the square; and every face is drawn after the faces it hides.
"""
import sys

import kvot_icon as K

OUT = K.ROOT / 'resources/images/winnetkakort-icon.svg'
PNG32 = K.ROOT / 'resources/images/winnetkakort-icon-32.png'
PNG180 = K.ROOT / 'resources/images/winnetkakort-icon-180.png'

# The inputs, in world units: the drawing is scaled to the square afterwards.
ACROSS = 30         # the plus, end to end
STROKE = 9          # an arm's width: a bold plus, as on a card held up in class
DEPTH = 8           # its depth, as it shows on screen

COMMENT = f'''\t<!--
\t\tA plus sign: the arithmetic Winnetkakort practises, addition first.

{K.RULES}

\t\tThe plus is its outline in one upright plane, extruded towards the
\t\tviewer, so its face is the right-hand tone and its top and left
\t\tedges show in the other two, as the letters of the other icons do.
\t\tIts arms are thick enough to stay a plus at sixteen pixels.

\t\tGenerated by scripts/gen-winnetkakort-icon.py, not typed. Change the
\t\tinputs there and run it again rather than editing the numbers here.
\t-->
'''


def outline():
    a, b = (ACROSS - STROKE) / 2, (ACROSS + STROKE) / 2
    return [(a, 0), (b, 0), (b, a), (ACROSS, a), (ACROSS, b), (b, b), (b, ACROSS), (a, ACROSS),
            (a, b), (0, b), (0, a), (a, a)]


def main():
    faces, _ = K.order([K.upright(outline(), 0, DEPTH / K.S)])
    placed, _ = K.place(faces)
    errors = K.problems(placed)
    if errors:
        sys.exit('not written:\n  ' + '\n  '.join(errors))
    # Each tone in at least half the share measured when the icon was drawn.
    K.write(OUT, PNG32, PNG180, K.svg(placed, 'Winnetkakort', COMMENT, (('the plus', len(placed)),)),
            {K.TOP: 0.03, K.RIGHT: 0.07}, {K.TOP: 0.025, K.RIGHT: 0.05, K.LEFT: 0.025})


if __name__ == '__main__':
    main()
