#!/usr/bin/env python3
"""Emit pylab's icon (pylab.html): resources/images/pylab-icon.svg, and from
it pylab-icon-32.png (the fallback) and pylab-icon-180.png (the touch icon,
for an iPhone's home screen).

    python3 scripts/gen-pylab-icon.py            # the SVG and the two PNGs
    python3 scripts/gen-pylab-icon.py --svg-only

The drawing is the Command Window's prompt, >>, in the kvot mark's isometric
language (scripts/kvot_icon.py); the SVG's own comment says why. Edit the
inputs below, never the numbers in the SVG.

Nothing is written unless every edge is horizontal, vertical or at the
chevrons' slant (30 degrees, made steeper by STRETCH); the drawing fits the
square; and every face is drawn after the faces it hides.
"""
import math
import sys

import kvot_icon as K

OUT = K.ROOT / 'resources/images/pylab-icon.svg'
PNG32 = K.ROOT / 'resources/images/pylab-icon-32.png'
PNG180 = K.ROOT / 'resources/images/pylab-icon-180.png'

# The inputs, in world units: the drawing is scaled to the square afterwards.
ARM = 11            # an arm of a chevron, from the point to its end
STEM = 4            # an arm's width
HEIGHT = 2.5        # the slab's thickness
STEP = 9            # the second chevron's point beyond the first, along x and u alike:
                    # a gap of two pixels at sixteen (unstretched, at 8 the two merge); a
                    # thicker slab fills the notch with its shaded face and reads as a play sign
STRETCH = 1.5       # the drawing this many times taller for its width than true
                    # isometric: arms rising at 41 degrees, not 30, as the prompt's do
SLANT = math.degrees(math.atan(STRETCH * math.tan(math.pi / 6)))

COMMENT = f'''\t<!--
\t\tThe prompt the Command Window waits at, two chevrons.

{K.RULES}

\t\tOne rule is bent here: the drawing is stretched upright, {STRETCH:g} times
\t\ttaller for its width than true isometric, so that the arms rise at
\t\t{SLANT:.0f} degrees rather than 30 and the chevrons stand like the prompt's.
\t\tEach face keeps its tone.

\t\tA chevron cannot be drawn upright: its arms would leave the three
\t\taxes. Lying flat it can. An L-shaped slab whose arms run back along
\t\tthe two ground axes from a corner nearest the right shows on screen
\t\tas a point with arms rising and falling at 30 degrees to the left,
\t\tthat is, as a chevron. Its top is the lit tone; the shaded edge under
\t\tthe upper arm and the right-hand face under the lower arm give it its
\t\tthickness. The second chevron is the first moved to the right.

\t\tGenerated by scripts/gen-pylab-icon.py, not typed. Change the inputs
\t\tthere and run it again rather than editing the numbers here.
\t-->
'''


def chevron(x, u):
    """The L with its corner at (x, u) and its arms along -x and -u."""
    return [(x - ARM, u - STEM), (x - STEM, u - STEM), (x - STEM, u - ARM),
            (x, u - ARM), (x, u), (x - ARM, u)]


def main():
    first = K.flat(chevron(0, 0), 0, HEIGHT)
    second = K.flat(chevron(STEP, STEP), 0, HEIGHT)
    faces, _ = K.order([first, second])
    placed, _ = K.place(faces, stretch=STRETCH)
    errors = K.problems(placed, STRETCH)
    if errors:
        sys.exit('not written:\n  ' + '\n  '.join(errors))
    half = len(placed) // 2
    # Each tone in at least half the share measured when the icon was drawn.
    K.write(OUT, PNG32, PNG180, K.svg(placed, 'PyLAB', COMMENT, (('the first chevron', half), ('the second', len(placed) - half))),
            {K.TOP: 0.032, K.RIGHT: 0.008}, {K.TOP: 0.029, K.RIGHT: 0.01, K.LEFT: 0.009})


if __name__ == '__main__':
    main()
