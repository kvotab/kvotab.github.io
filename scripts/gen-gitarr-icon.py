#!/usr/bin/env python3
"""Emit the guitar tuner's icon (gitarr.html): resources/images/
gitarr-icon.svg, and from it gitarr-icon-32.png (the fallback) and
gitarr-icon-180.png (the touch icon, for an iPhone's home screen).

    python3 scripts/gen-gitarr-icon.py            # the SVG and the two PNGs
    python3 scripts/gen-gitarr-icon.py --svg-only

The drawing is a tuning fork, in the kvot mark's isometric language
(scripts/kvot_icon.py); the SVG's own comment says why. Edit the inputs
below, never the numbers in the SVG.

Nothing is written unless every edge is horizontal, vertical or at 30 degrees;
the drawing fits the square; the prongs are a pixel apart at sixteen pixels;
and every face is drawn after the faces it hides.
"""
import sys

import kvot_icon as K

OUT = K.ROOT / 'resources/images/gitarr-icon.svg'
PNG32 = K.ROOT / 'resources/images/gitarr-icon-32.png'
PNG180 = K.ROOT / 'resources/images/gitarr-icon-180.png'

# The inputs, in world units: the drawing is scaled to the square afterwards.
STROKE = 6          # a prong's width, and the stem's
GAP = 12            # between the prongs
HANDLE = 16         # the stem, up to the bow
BOW = 6             # the bow joining the prongs
PRONGS = 24         # the prongs, above the bow
DEPTH = 7           # its depth, as it shows on screen

COMMENT = f'''\t<!--
\t\tA tuning fork: what tuned a guitar before there was a phone to do it.

{K.RULES}

\t\tThe fork is its outline in one upright plane, extruded towards the
\t\tviewer: a stem, a bow and two prongs, as square in section as the
\t\tkvot mark's bars. The far prong stands higher on screen, as the
\t\tright-hand end of anything does in this projection.

\t\tGenerated by scripts/gen-gitarr-icon.py, not typed. Change the inputs
\t\tthere and run it again rather than editing the numbers here.
\t-->
'''


def outline():
    width = 2 * STROKE + GAP
    s0, s1 = (width - STROKE) / 2, (width + STROKE) / 2
    bow, top = HANDLE + BOW, HANDLE + BOW + PRONGS
    return [(s0, 0), (s1, 0), (s1, HANDLE), (width, HANDLE), (width, top), (width - STROKE, top),
            (width - STROKE, bow), (STROKE, bow), (STROKE, top), (0, top), (0, HANDLE), (s0, HANDLE)]


def main():
    faces, _ = K.order([K.upright(outline(), 0, DEPTH / K.S)])
    placed, k = K.place(faces)
    errors = K.problems(placed)
    if GAP * K.S * k < K.SIZE / 16:
        errors.append(f'the prongs are {GAP * K.S * k / 4:.2f} px apart at 16 px, under a pixel')
    if errors:
        sys.exit('not written:\n  ' + '\n  '.join(errors))
    # Each tone in at least half the share measured when the icon was drawn:
    # the fork's lit tops are thin.
    K.write(OUT, PNG32, PNG180, K.svg(placed, 'Gitarrstämmare', COMMENT, (('the fork', len(placed)),)),
            {K.TOP: 0.006, K.RIGHT: 0.04}, {K.TOP: 0.008, K.RIGHT: 0.03, K.LEFT: 0.03})


if __name__ == '__main__':
    main()
