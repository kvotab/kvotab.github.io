#!/usr/bin/env python3
"""Emit Blockmodellen's icon (blockmodellen.html): resources/images/
blockmodellen-icon.svg, and from it blockmodellen-icon-32.png (the fallback)
and blockmodellen-icon-180.png (the touch icon, which an iPhone puts on its
home screen, from Safari or from Chrome).

    python3 scripts/gen-blockmodellen-icon.py            # the SVG and the two PNGs
    python3 scripts/gen-blockmodellen-icon.py --svg-only

The drawing is a block model of a comparison, in the kvot mark's isometric
language (scripts/kvot_icon.py); the SVG's own comment says why. Edit the
inputs below, never the numbers in the SVG.

Nothing is written unless every edge is horizontal, vertical or at 30 degrees;
the drawing fits the square; the dark side that parts the two bits of the long
bar, and the gap between the bars, are each a pixel or more at sixteen pixels;
and every face is drawn after the faces it hides.
"""
import sys

import kvot_icon as K

OUT = K.ROOT / 'resources/images/blockmodellen-icon.svg'
PNG32 = K.ROOT / 'resources/images/blockmodellen-icon-32.png'
PNG180 = K.ROOT / 'resources/images/blockmodellen-icon-180.png'

# The inputs, in world units: the drawing is scaled to the square afterwards.
BIT = 20            # the bit both bars have, along the bars
EXTRA = 11          # the other bit, the difference, that sticks out
PART = 4.5          # between the two bits of the long bar: a divider, not a gap
BAR = 12            # a bar's height: short, thick bars, or at tab size they are two sticks
APART = 9           # between the bars, foot to top
DEPTH = 6           # the bars' depth, as it shows on screen: bars drawn, not bricks
LONG_ON_TOP = False # the short bar above the long one, as the page draws a comparison


def pieces(bit=BIT, extra=EXTRA, part=PART, bar=BAR, apart=APART, depth=DEPTH, long_on_top=LONG_ON_TOP):
    """The three blocks, as boxes in one upright plane extruded towards the
    viewer: the short bar's bit, and the long bar's bit and its extra bit."""
    d = depth / K.S
    low, high = (0, bar), (bar + apart, 2 * bar + apart)
    long_z, short_z = (high, low) if long_on_top else (low, high)
    return [
        K.box(0, d, 0, bit, *short_z),
        K.box(0, d, 0, bit, *long_z),
        K.box(0, d, bit + part, bit + part + extra, *long_z),
    ]


def check(shapes, k, part=PART, apart=APART, depth=DEPTH):
    """What the rules ask beyond kvot_icon's: what parts the pieces, at 16 px.
    A unit of the square is a quarter of a pixel there. Between the two bits
    shows the extra bit's dark side, as wide as the gap between them; between
    the bars, what the lower bar's lit top leaves of the gap."""
    errors = []
    side = part * K.S * k
    if side < K.SIZE / 16:
        errors.append(f'the bits are parted by {side / 4:.2f} px at 16 px, under a pixel')
    gap = (apart - depth / (2 * K.S)) * k
    if gap < K.SIZE / 16:
        errors.append(f'the bars are {gap / 4:.2f} px apart at 16 px, under a pixel')
    return errors


COMMENT = f'''\t<!--
\t\tA block model of a comparison: two bars that begin at the same
\t\tplace, the short one above and the long one below, with a bit that
\t\tsticks out, their difference. That bit is what the model shows at a
\t\tglance, and what Blockmodellen teaches a pupil to draw, and to look
\t\tfor.

{K.RULES}

\t\tEach bit is a box in one upright plane, extruded towards the viewer:
\t\tits face is the right-hand tone, as the letters of the other icons
\t\tare, its top the lit tone. The extra bit's shaded side parts it from
\t\tthe bit before it, as the line between two bits does on paper.

\t\tLong thin bars were drawn first and dropped: at tab size they were
\t\ttwo sticks. Short thick ones fill the square and stay blocks.

\t\tGenerated by scripts/gen-blockmodellen-icon.py, not typed. Change the
\t\tinputs there and run it again rather than editing the numbers here.
\t-->
'''


def main():
    shapes = pieces()
    faces, _ = K.order(shapes)
    placed, k = K.place(faces)
    errors = K.problems(placed) + check(shapes, k)
    if errors:
        sys.exit('not written:\n  ' + '\n  '.join(errors))
    # Each tone in at least half the share measured when the icon was drawn.
    K.write(OUT, PNG32, PNG180, K.svg(placed, 'Blockmodellen', COMMENT, (('the bars', len(placed)),)),
            {K.TOP: 0.034, K.RIGHT: 0.073}, {K.TOP: 0.03, K.RIGHT: 0.054, K.LEFT: 0.02})


if __name__ == '__main__':
    main()
