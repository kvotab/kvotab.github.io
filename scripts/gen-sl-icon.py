#!/usr/bin/env python3
"""Emit the departure boards' icon (solna.html and uppsala.html): resources/
images/sl-icon.svg, and from it sl-icon-32.png (the fallback) and
sl-icon-180.png (the touch icon, for an iPhone's home screen).

    python3 scripts/gen-sl-icon.py            # the SVG and the two PNGs
    python3 scripts/gen-sl-icon.py --svg-only

The drawing is a departure sign on a post, three lines of departures on its
board, in the kvot mark's isometric language (scripts/kvot_icon.py); the
SVG's own comment says why. Edit the inputs below, never the numbers in the
SVG.

Nothing is written unless every edge is horizontal, vertical or at 30 degrees;
the drawing fits the square; and every face is drawn after the faces it hides.
"""
import sys

import kvot_icon as K

OUT = K.ROOT / 'resources/images/sl-icon.svg'
PNG32 = K.ROOT / 'resources/images/sl-icon-32.png'
PNG180 = K.ROOT / 'resources/images/sl-icon-180.png'

# The inputs, in world units: the drawing is scaled to the square afterwards.
POST = 6                         # the post's side
STANDS = 27                      # how high it stands under the board
BOARD = (-5, 31, 26, 47)         # the board's (u0, u1, z0, z1)
BOARD_X = (-1, 4)                # and its thickness, along x
DEPARTURES = [(22, 40), (16, 35), (19, 30)]   # each line's length along u and its height: the next three trains
LINE = 2.6                       # a line's height
STANDS_OUT = 1.6                 # and how far it stands out from the board

COMMENT = f'''\t<!--
\t\tA departure sign on a post, three lines of departures on its board:
\t\tthe next three trains, which is what these boards show.

{K.RULES}

\t\tThe board is its outline extruded towards the viewer, the post a
\t\tblock under it, and the departures low bars on the board's face, so
\t\twhat shows of them is their lit tops and shaded ends. At sixteen
\t\tpixels the lines go, and a sign on a post is left.

\t\tGenerated by scripts/gen-sl-icon.py, not typed. Change the inputs
\t\tthere and run it again rather than editing the numbers here.
\t-->
'''


def shapes():
    u0, u1, z0, z1 = BOARD
    middle = (u0 + u1) / 2
    post = K.box(BOARD_X[0] + 0.5, BOARD_X[0] + 0.5 + POST, middle - POST / 2, middle + POST / 2, 0, STANDS)
    board = K.upright([(u0, z0), (u1, z0), (u1, z1), (u0, z1)], *BOARD_X)
    x = BOARD_X[1]
    lines = [K.box(x, x + STANDS_OUT, u0 + 4, u0 + 4 + length, z, z + LINE) for length, z in DEPARTURES]
    return [post, board] + lines


def main():
    faces, seq = K.order(shapes())
    placed, _ = K.place(faces)
    errors = K.problems(placed)
    if errors:
        sys.exit('not written:\n  ' + '\n  '.join(errors))
    # Each tone in at least half the share measured when the icon was drawn:
    # the board's face is most of it, the lit tops thin.
    K.write(OUT, PNG32, PNG180, K.svg(placed, 'Avgångar', COMMENT, (('the post, the board and its departures', len(placed)),)),
            {K.TOP: 0.006, K.RIGHT: 0.04}, {K.TOP: 0.01, K.RIGHT: 0.04, K.LEFT: 0.012})


if __name__ == '__main__':
    main()
